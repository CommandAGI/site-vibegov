/** A translator over one group of WORDS: `words('refusals')('rfc_deposit', { amount })`. A key with no words is returned as it is. */
export const words = group => (key, values = {}) => {
  const text = WORDS[group ? `${group}.${key}` : key];
  if (text === undefined) return key;
  // `{count, plural, one {# response} other {# responses}}`, then `{name}`.
  return text
    .replace(/\{(\w+), plural, one \{([^{}]*)\} other \{([^{}]*)\}\}/g, (m, name, one, other) => (Number(values[name]) === 1 ? one : other).replaceAll('#', String(values[name] ?? '')))
    .replace(/\{(\w+)\}/g, (m, name) => (name in values ? String(values[name]) : m));
};
/** Whether WORDS has these words (a refusal code the catalog does not know is shown as its code). */
export const hasWords = (group, key) => WORDS[group ? `${group}.${key}` : key] !== undefined;

